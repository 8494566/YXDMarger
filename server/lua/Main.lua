		for i in GLOBAL_DataSaveTable do
			if type(GLOBAL_DataSaveTable[i]) == 'table' then
				for j in GLOBAL_DataSaveTable[i] do
					if type(GLOBAL_DataSaveTable[i][j]) == 'table' then
						for k in GLOBAL_DataSaveTable[i][j] do
							if type(GLOBAL_DataSaveTable[i][j][k]) == 'number' then
								API_VarDataSave_Ex(i,j,k)
							end
						end
						for n,v in pairs(GLOBAL_DataSaveTable[i][j]) do
							--API_Trace('key:'..tostring(n).." = "..tostring(v));
							API_VarDataSave_Ex(i,j,v)
						end
					end
				end
			end
		end
	end
