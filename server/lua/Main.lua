			--城战数据
			for i = -63,-22 do
				if API_VarDataGetNumber_Ex(1,0,i,1,170) == 0 then
					break
				end
				if i == - 22 then
					CastteBette_Info_OnLoadIDataOK = 1
				end
			end
		elseif OwnerID == -100 then
			--运营活动数据
			OperationsReward_OnLoadIDataOK = 1
		elseif OwnerID == -101 then
			if API_GetServerID() == 1 then
				if API_VarDataGetNumber_Ex(1,0,OwnerID,1,8) == 0 then
					local Year,Month,Day,Hour,Minute,Second,Week = PublicFun_time()
					API_VarDataSetNumber_Ex_Sync(1,0,OwnerID,1,1,Year)
					API_VarDataSetNumber_Ex_Sync(1,0,OwnerID,1,2,Month)
					API_VarDataSetNumber_Ex_Sync(1,0,OwnerID,1,3,Day)
					API_VarDataSetNumber_Ex_Sync(1,0,OwnerID,1,4,Hour)
