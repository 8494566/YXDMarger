--判断是否处理任务/功能
function Task_CanUse(ActorID,TaskID)
	if TaskID == 3028 then
		--生活技能分支转换
		for i = 15,21 do
			if API_GetWorkSkillLevel(ActorID,i) ~= 0 and API_GetActorWSTechBranchID(ActorID,i) ~= 0 then
				return 1
			end
		end
		return 0
	elseif TaskID == 3028 then
		--生活技能遗忘
		return 1
	elseif TaskID == 1728 then
		--知识达人活动报名
		if API_GetActorExpLevel(ActorID) < 11 then
			return 0
		end
		local Year,Month,Day,Hour,Minute,Second,Week = PublicFun_time()
		if Week == 6 or Week == 7 then
			if Hour >= 12 and Hour <= 17 then
			else
				return 0
			end
		else
			return 0
		end
	elseif TaskID == 1729 then
		--知识达人活动介绍
		if API_GetActorExpLevel(ActorID) < 11 then
			return 0
		end
		local Year,Month,Day,Hour,Minute,Second,Week = PublicFun_time()
		if Week == 6 or Week == 7 then
			if Hour >= 12 and Hour <= 17 then
			else
				return 0
			end
		else
			return 0
		end
	end
	return 1
end


