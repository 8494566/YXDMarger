		local NonceConstructNum = 0
		local GrantConstructNum = GLOBAL_BATTLE_GrantConstructNum[StaticMapID] + math.floor(PeerageLevel/2)
		for i = 1,table.getn(GLOBAL_BATTLE_ConstructList[MapID][ActorID]) do
