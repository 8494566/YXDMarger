--建设官游戏提示
function NPCDialog_Tip_Jiansheguan(ActorID, NPCID)
	local PeerageLevel = API_GetActorPeerageLevel(ActorID)
	local MapID = API_GetActorMapID(ActorID)
	local StaticMapID = API_GetStaticMapID(MapID)
	if StaticMapID == MapID then
		API_ResponseWrite('<br><text color="0,255,255">您只能在副本地图中使用建筑功能</text><br>')
		return
	end
	if type(GLOBAL_BATTLE_ConstructList[MapID]) == 'table' then
		if type(GLOBAL_BATTLE_ConstructList[MapID][ActorID]) ~= 'table' then
			API_ResponseWrite('<br><text color="0,255,255">您没有加入这场地图的战争</text><br>')
			return
		end
	else
		API_ResponseWrite('<br><text color="0,255,255">本地图没有发生战争</text><br>')
		return
	end
	if GLOBAL_BATTLE_GrantConstructNum[StaticMapID] ~= nil then
		local NonceConstructNum = 0
		local GrantConstructNum = GLOBAL_BATTLE_GrantConstructNum[StaticMapID] + math.floor(PeerageLevel/2)
		for i = 1,table.getn(GLOBAL_BATTLE_ConstructList[MapID][ActorID]) do
			local ConstructFastID = GLOBAL_BATTLE_ConstructList[MapID][ActorID][i]
			if API_GetMonsterID(ConstructFastID) ~= -1 then
				NonceConstructNum = NonceConstructNum + 1
			end
		end
		if NonceConstructNum >= GrantConstructNum then
			API_ResponseWrite('<br><text color="0,255,255">您当前拥有建筑数量已达到允许建筑上限，继续购买图纸将不能使用</text><br>')
			return
		end
		API_ResponseWrite('<br><text color="255,0,255">您当前拥有建筑数量/允许建筑数量：'..NonceConstructNum..'/'..GrantConstructNum..'</text><br>')
	else
		API_ResponseWrite('<br><text color="0,255,255">当前地图不允许建造建筑</text><br>')
	end
end

