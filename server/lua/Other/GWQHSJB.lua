function GWQHSJB_OnLogin(ActorID)
	local Num = API_ActorGetGoodsNum(ActorID, 80289)
	if Num > 0 then
		if API_ActorRemoveGoods(ActorID,80289,Num,"删除购物券") then
			API_ActorShoppingM_Add(ActorID,Num,0, "添加水晶币")
		end
	end
end 
