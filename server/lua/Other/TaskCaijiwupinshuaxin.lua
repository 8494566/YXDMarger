function Task_caiji_dibiao_shuaxin(MapID,goodsID,num)
	if not API_MapIsValid(MapID) then
		return
	end	
	if type(Task_caiji_dibiao_GOODSIDtable1[MapID][goodsID])=="table"  and Task_caiji_dibiao_GOODSIDtable1[MapID][goodsID] ~= nil then
		local zuobiao
		local StaticMapID = API_GetMapConfigID(MapID) --配置地图ID
		if type(Task_caiji_dibiao_GOODSIDtable[StaticMapID])=="table"  and Task_caiji_dibiao_GOODSIDtable[StaticMapID] ~= nil then
			for w in Task_caiji_dibiao_GOODSIDtable[StaticMapID] do
				if Task_caiji_dibiao_GOODSIDtable[StaticMapID][w].goodsID  == goodsID then
					zuobiao = Task_caiji_dibiao_GOODSIDtable[StaticMapID][w].zuobiao
					break
				end
			end
		end
		if type(zuobiao)=="table" then
			local biaochang = table.getn(zuobiao)
			for h = 1, num do				
				local index = 0
				local x = 0
				local y = 0	
				local cishu = 0					
				repeat
					index = math.random(1,biaochang)
					if not zuobiao[index] then
						break 
					end
					x = zuobiao[index].x
					y = zuobiao[index].y
					cishu = cishu + 1
				until not API_IsBlockTile(MapID,x,y,0) or cishu == 50
				local UID = API_CreateResBoxEx_RetUIDHigh(MapID,x,y,goodsID,1,'采集任务产出',0)		--测试 goodsID
				local UIDL = API_GetUIDLow()
				if UID > 0 and UIDL > 0 then
					if Task_caiji_dibiao_GOODSIDtable1 == nil then
						Task_caiji_dibiao_GOODSIDtable1 = {}
					end
					if Task_caiji_dibiao_GOODSIDtable1[MapID] == nil then
						Task_caiji_dibiao_GOODSIDtable1[MapID] = {}
					end
					if Task_caiji_dibiao_GOODSIDtable1[MapID][goodsID] == nil then
						Task_caiji_dibiao_GOODSIDtable1[MapID][goodsID] = {}
					end
					
					for k in Task_caiji_dibiao_GOODSIDtable1[MapID][goodsID] do
						if Task_caiji_dibiao_GOODSIDtable1[MapID][goodsID][k] ~= nil then
							if Task_caiji_dibiao_GOODSIDtable1[MapID][goodsID][k].High == 0 then
								Task_caiji_dibiao_GOODSIDtable1[MapID][goodsID][k].High = UID
								Task_caiji_dibiao_GOODSIDtable1[MapID][goodsID][k].Low = UIDL
								break
							end
						end
					end
				end
			end
		end 
	end
