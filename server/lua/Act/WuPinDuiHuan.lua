			local LocID1 =  API_VarDataGetNumber(ActorID,1,19290)
			if API_ActorRemoveGoodsOfLoc(ActorID,GoodsID,1,BoxID1,LocID1, '删除1个'..API_GetGoodsName(GoodsID)..'兑换奖励')  then
				API_OpenIconTiger(ActorID,TigerID,JiangLiPlace,'宝箱娃娃','WuPinDuiHuan_IconTigerAgainFunc','WuPinDuiHuan_IconTigerPickFunc',16,WuPinIconTigerList)
				GoldKeynum = GoldKeynum + 1
				API_VarDataSetNumber_Ex_Sync(1, 0, -5001, 1, MapKey , GoldKeynum )
				GoldCoinNum  = GoldCoinNum  + 1
				API_VarDataSetNumber(ActorID,1,19286,GoldCoinNum )
				GoldNumber  =  GoldNumber	+  1
				API_VarDataSetNumber_Ex_Sync(1, 0, -5001, 1, 34 , GoldNumber )
				if  	math.mod(GoldKeynum,99999999) == 0  or  math.mod(GoldCoinNum,99999999) ==  0 	then
