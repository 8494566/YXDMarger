					local ShowGoodsTab1 = {}
					ShowGoodsTab1.GoodsID = JiangLiGoodsID 
					ShowGoodsTab1.GoodsNum = JiangLiGoodsNum 
					table.insert(RandomIconTigerList,ShowGoodsTab1 )
					ShowNum = ShowNum -1
				else	
