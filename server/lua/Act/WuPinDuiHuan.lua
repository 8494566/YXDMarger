			local WuPinIconTigerList = {}
			for i = 1,table.getn(RandomIconTigerList) do
				local WuPinXuHao = table.getn(WuPinIconTigerList) + 1
				if WuPinIconTigerList[WuPinXuHao] == nil then
					WuPinIconTigerList[WuPinXuHao] = {}
				end
				WuPinIconTigerList[WuPinXuHao] = RandomIconTigerList[i].GoodsID
				WuPinIconTigerList[WuPinXuHao + 1] = RandomIconTigerList[i].GoodsNum
			end
			local  oMapID  = API_GetActorMapID(ActorID)
