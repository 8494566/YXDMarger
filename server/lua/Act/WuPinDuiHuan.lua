					ShowGoodsTab2.GoodsID = ShowGoodsID 
					ShowGoodsTab2.GoodsNum = ShowGoodsNum
					table.insert(RandomIconTigerList,ShowGoodsTab2 )
					ShowNum = ShowNum -1
				end
			end		
