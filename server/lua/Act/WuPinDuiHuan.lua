						repeat
							--x = math.random(625)
							--y = math.random(624)
							x = math.random(X1,X2)
							y = math.random(Y1,Y2)
						until not API_IsBlockTile(oMapID,x,y,0)
						API_CreateDropGoods(oMapID,x,y,88941,1,3,'宝箱',4,0,600,0)
					end
