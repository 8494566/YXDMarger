						API_ActorBroadcastMsgEx(-1,-1,0,17,''..ActorName..'在'..MapName..'进行宝箱娃娃兑换，当前地图累计达到'..GoldKeynum..'次，'..MapName..'将会出现100个宝箱，拾取打开宝箱可获得丰厚奖励，先到先得。')
