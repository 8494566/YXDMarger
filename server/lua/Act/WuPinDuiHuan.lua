					end
					if	math.mod(GoldCoinNum,99999999) == 0 then
						API_ActorBroadcastMsgEx(-1,-1,0,17,''..ActorName..'在'..MapName..'进行宝箱娃娃兑换，个人兑换已经累计达到'..GoldCoinNum..'次，'..MapName..'将会出现100个宝箱，拾取打开宝箱可获得丰厚奖励，先到先得。')
						API_ActorBroadcastMsgEx(-1,-1,0,8,''..ActorName..'在'..MapName..'进行宝箱娃娃兑换，个人兑换已经累计达到'..GoldCoinNum..'次，'..MapName..'将会出现100个宝箱，拾取打开宝箱可获得丰厚奖励，先到先得。')
					end	
					--风向标
					local LaiYuan = API_ActorGetPropNum(ActorID,201)
					local Type = 4
					if GLOBAL_FengXiangBiao_DateList[52][Type][LaiYuan] == nil then
						GLOBAL_FengXiangBiao_DateList[52][Type][LaiYuan] = 1
					else
						GLOBAL_FengXiangBiao_DateList[52][Type][LaiYuan] = GLOBAL_FengXiangBiao_DateList[52][Type][LaiYuan] + 1
					end
				end
			end
		else
			return
		end	
	else
		return
	end	
end
