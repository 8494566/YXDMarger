			elseif	GoldNumber > 2000 then
				MonsterLevel = "三"
			end	
			API_ActorBroadcastMsgEx(-1,-1,0,17,'今天累计兑换周年金币达到'..GoldNumber..'次，'..MonsterLevel..'级周年财兔已经出现在(帝国：暗礁海)、(联邦：麦穗平原)、沙暴绿洲！杀死怪物将有几率获得周年金币')
