--创建怪物	
function Goldtest_wb_CreateMonsterFunc()
	local GoldNumber  = API_VarDataGetNumber_Ex(1, 0, -5001, 1, 34 )
	if	API_VarDataGetNumber_Ex(1, 0, -5001, 1, 35)	==	0	then
		API_VarDataSetNumber_Ex_Sync(1, 0, -5001, 1, 35, GoldNumber)
	end	
	local GoldNumber  = API_VarDataGetNumber_Ex(1, 0, -5001, 1, 35 )	
	local MonsterLevel = "一"
	local MonsterID1 = 730001
	local MonsterID2 = 730004
	if GoldNumber > 1000  and GoldNumber  <= 2000	then
		MonsterLevel = "二"
		MonsterID1 = 730002
		MonsterID2 = 730005
	elseif GoldNumber > 2000 then
		MonsterLevel = "三"
		MonsterID1 = 730003
		MonsterID2 = 730006
	end	
	for j in Goldtest_wb_CreateMonsterMap do
		local RightMapID = API_GetRightMapID(j)
		if API_MapIsValid(RightMapID) then
			local PlayNum = 0
			local PlayList = API_GetActorInArea(RightMapID, 0, 0, 0, 0, 0)
			local X1,X2,Y1,Y2 = Goldtest_wb_CreateMonsterMap[j].X1,Goldtest_wb_CreateMonsterMap[j].X2,Goldtest_wb_CreateMonsterMap[j].Y1,Goldtest_wb_CreateMonsterMap[j].Y2
			if PlayList ~= nil then
				PlayNum = table.getn(PlayList)
			end
			local MonNum = 1
			if	PlayNum	<=	50	then
				MonNum = 150
			elseif	PlayNum > 50 and PlayNum <= 100 then
				MonNum = 150+ (PlayNum  - 50)*3
			elseif	PlayNum > 100	then
				MonNum = 300
			end	
			for i = 1,MonNum do
				local locx,locy
				repeat
					locx = math.random(X1,X2)
					locy = math.random(Y1,Y2)
				until not API_IsBlockTile(RightMapID,locx,locy,0)
				if j == 102 then
					local FastID = API_CreateMonster(RightMapID, MonsterID2, locx,locy, 3, 0, -1)
					table.insert(Goldtest_wb_MonsterList,FastID)
					API_CreateDieTriggerG(PlayNum,RightMapID,0,FastID,'Goldtest_wb_DieTriggerGFunc')	
				else
					local FastID = API_CreateMonster(RightMapID, MonsterID1, locx,locy, 3, 0, -1)
					table.insert(Goldtest_wb_MonsterList,FastID)
					API_CreateDieTriggerG(PlayNum,RightMapID,0,FastID,'Goldtest_wb_DieTriggerGFunc')	
				end
			end
			
		end
	end
	API_ActorBroadcastMsgEx(-1,-1,0,8,'今天累计兑换周年金币达到'..GoldNumber..'次，'..MonsterLevel..'级周年财兔已经出现在(帝国：暗礁海)、(联邦：麦穗平原)、沙暴绿洲！杀死怪物将有几率获得周年金币')
end
